const NONE: readonly string[] = []

/** The people (or, rarely, organisations) credited with a node. Empty if unknown. */
export const creatorsOf = (id: string): readonly string[] => CREATORS[id] ?? NONE

/** Every node id a given name is credited on, for "what else did they make". */
export function creditsOf(name: string): string[] {
  const out: string[] = []
  for (const id in CREATORS) if (CREATORS[id].includes(name)) out.push(id)
  return out
}
